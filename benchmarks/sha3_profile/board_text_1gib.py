#!/usr/bin/env python3
"""Generate a 1 GiB ASCII file on Zybo SD and compare both physical SHA3 cores.

Upload this small program and demo/core_variants.json over UART. Payload bytes
are generated on the board, never sent over UART. Memory is bounded to chunks.
Installed firmware/configuration is verified and never replaced.
"""
import argparse
from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import signal
import statistics
import subprocess
import sys
import time

BASE = Path('/opt/zybo/hash')
SIZE = 1 << 30
CHUNK = 1 << 20
WARMUP = 16 << 20
ALPHABET = b'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
TABLE = bytes(ALPHABET[i & 63] for i in range(256))
EXPECTED = {
    'dfx_manifest.json': '0ea0df9299508deac45af403960d484f892c723b0d029177e504bb02eb773ab3',
    'software/hash_service.py': '408dd039f9cdc30b5c275ee980470df7b93c81dd2a15a9170e6727a94aa58edb',
    'software/hash_local.py': '2f75a71a2d19e18e920f58f075eb66f0e35250f8668abdfb84902c0c97e2996c',
}


def sha(path):
    with Path(path).open('rb') as source:
        return hashlib.file_digest(source, 'sha256').hexdigest()


def emit(event, **values):
    print(json.dumps(dict(event=event, monotonic_seconds=time.monotonic(), **values)), flush=True)


def save(path, report):
    temp = path.with_suffix('.json.tmp')
    with temp.open('w') as out:
        json.dump(report, out, indent=2); out.write('\n'); out.flush(); os.fsync(out.fileno())
    temp.replace(path)


def evict(path):
    # File-scoped advice: no global drop_caches or unrelated cache eviction.
    with path.open('rb') as source:
        os.posix_fadvise(source.fileno(), 0, 0, os.POSIX_FADV_DONTNEED)


def fingerprint(path):
    s = path.stat()
    return (s.st_dev, s.st_ino, s.st_size, s.st_mtime_ns)


def generate(path):
    h = hashlib.sha256(); started = time.perf_counter_ns()
    with path.open('xb') as out:
        for index in range(SIZE//CHUNK):
            block = bytearray(os.urandom(CHUNK).translate(TABLE))
            block[127::128] = b'\n'*(CHUNK//128)
            out.write(block); h.update(block)
            if (index+1) % 64 == 0:
                emit('generating', bytes=(index+1)*CHUNK, total=SIZE)
        out.flush(); os.fsync(out.fileno())
    path.chmod(0o444)
    assert path.stat().st_size == SIZE
    return dict(bytes=SIZE, sha256=h.hexdigest(), elapsed_ns=time.perf_counter_ns()-started,
                generator='os.urandom; uniform 64-character ASCII alphabet; 127 characters then LF',
                alphabet=ALPHABET.decode(), line_bytes=128, lines=SIZE//128)


def reference(path, expected_sha):
    evict(path); sha3 = hashlib.sha3_256(); sha256 = hashlib.sha256(); prefix = hashlib.sha3_256()
    count = 0; started = time.perf_counter_ns()
    with path.open('rb') as source:
        while block := source.read(CHUNK):
            if block.translate(None, ALPHABET+b'\n') or block[127::128] != b'\n'*(len(block)//128):
                raise RuntimeError('Generated file is not the expected ASCII text')
            sha3.update(block); sha256.update(block)
            if count < WARMUP:
                prefix.update(block[:min(len(block), WARMUP-count)])
            count += len(block)
            if count % (64*CHUNK) == 0:
                emit('software_reference', bytes=count, total=SIZE)
    if count != SIZE or sha256.hexdigest() != expected_sha:
        raise RuntimeError('Persisted file differs from the generated bytes')
    return dict(bytes=count, sha3_256=sha3.hexdigest(), sha256=sha256.hexdigest(),
                warmup_prefix_sha3_256=prefix.hexdigest(), elapsed_ns=time.perf_counter_ns()-started,
                timing_scope='Reference readback, text validation, SHA-256 and SHA3; outside all FPGA timings')


class TimedReader:
    def __init__(self, source):
        self.source = source; self.read_ns = 0; self.bytes_read = 0

    def readinto(self, target):
        started = time.perf_counter_ns()
        count = self.source.readinto(target)
        self.read_ns += time.perf_counter_ns()-started
        self.bytes_read += count
        return count


def measure(hasher, path):
    evict(path)
    transfer = hasher._hardware.transfer
    dma_ns = 0; calls = 0

    def timed_transfer(count):
        nonlocal dma_ns, calls
        started = time.perf_counter_ns()
        transfer(count)
        dma_ns += time.perf_counter_ns()-started; calls += 1

    hasher._hardware.transfer = timed_transfer
    try:
        with path.open('rb') as source:
            os.posix_fadvise(source.fileno(), 0, 0, os.POSIX_FADV_SEQUENTIAL)
            reader = TimedReader(source)
            result = hasher.hash_stream(reader, SIZE, 'sha3', verify=False)
    finally:
        hasher._hardware.transfer = transfer
    assert reader.bytes_read == SIZE and calls == result['dma_transfers'] == SIZE//CHUNK
    result.update(file_read_ns=reader.read_ns, dma_calls_ns=dma_ns,
                  other_local_api_ns=result['local_hash_ns']-reader.read_ns-dma_ns,
                  cache_policy='File-scoped POSIX_FADV_DONTNEED before trial; POSIX_FADV_SEQUENTIAL during read',
                  timing_scope='SD file read + local API + driver + DMA + core; excludes generation, software reference and reconfiguration',
                  dma_timing_scope='Sum of synchronous DMA transfer call durations; includes driver and hardware backpressure, excludes SD read calls; not pure core compute')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--variants', type=Path, required=True)
    args = parser.parse_args()
    if args.output_dir.parent != Path('/root') or not args.output_dir.name.startswith('hash-bench-1gib-'):
        parser.error('Use a fresh /root/hash-bench-1gib-* directory')
    if Path('/proc/device-tree/model').read_bytes().rstrip(b'\0') != b'Digilent Zybo Z7-20 DFX hash accelerator':
        raise RuntimeError('Hash profile required')
    actual = {name:sha(BASE/name) for name in EXPECTED}
    if actual != EXPECTED:
        raise RuntimeError('Installed software or manifest differs from the pinned configuration')
    sys.path.insert(0, str(BASE/'software'))
    from hash_local import LocalHasher
    from hash_service import firmware_path
    base = json.loads((BASE/'dfx_manifest.json').read_text())
    config = json.loads(args.variants.read_text())
    if any(config[k] != base[k] for k in ('abi', 'part', 'static_sha256')):
        raise RuntimeError('Static design identity mismatch')
    if sha('/boot/profiles/hash/system.bit') != base['static_sha256']:
        raise RuntimeError('Full bitstream checksum mismatch')
    if sha('/boot/profiles/hash/system.dtb') != '3d2809a8f625f698e720bc6254e9520ceb233d2d3c79192dcfe0933bbe6e25ed':
        raise RuntimeError('Device tree checksum mismatch')
    if set(config['variants']) != {'oxide', 'compact'} or config['variants']['compact']['image'] != base['images']['sha3']:
        raise RuntimeError('Comparison images differ from the installed default')
    for variant in config['variants'].values():
        if variant['image']['algorithm_id'] != 1 or sha(firmware_path(variant['image']['filename'])) != variant['image']['sha256']:
            raise RuntimeError('Partial image checksum or algorithm mismatch')
    if not hasattr(os, 'posix_fadvise'):
        raise RuntimeError('File-scoped cache advice is required')
    disk = os.statvfs('/root')
    if disk.f_bavail*disk.f_frsize < SIZE+(1<<30):
        raise RuntimeError('Need room for the file plus at least 1 GiB free')
    args.output_dir.mkdir(mode=0o700)
    path = args.output_dir/'random-1gib.txt'; output = args.output_dir/'results.json'
    report = dict(state='running', file=str(path), kernel=os.uname().release,
                  source_sha256=sha(__file__), variants_sha256=sha(args.variants),
                  installed_checksums=actual, static_sha256=base['static_sha256'],
                  profile_env_before=sha('/boot/profile.env'), samples=[], warmups=[],
                  order=['oxide','compact','compact','oxide','oxide','compact'],
                  repeats_per_core=3, warmup_bytes=WARMUP)
    save(output, report)
    try:
        emit('generation_started', file=str(path), bytes=SIZE)
        report['generation'] = generate(path); save(output, report)
        report['reference'] = reference(path, report['generation']['sha256']); save(output, report)
        original = fingerprint(path)
        starter = str(BASE/'start.sh'); safe_to_restart = True
        try:
            subprocess.run([starter, 'stop'], check=True, stdout=subprocess.DEVNULL)
            subprocess.run(['modprobe','hash_accel'],check=True)
            with LocalHasher(manifest=BASE/'dfx_manifest.json') as hasher:
                try:
                    for index, core in enumerate(report['order']):
                        safe_to_restart = False
                        hw = hasher._hardware; hw.manifest = deepcopy(base)
                        hw.select('sha256')
                        if hw.info()[1] != 2:
                            raise RuntimeError('Intermediate SHA-256 image was not observed')
                        image = config['variants'][core]['image']; hw.manifest['images']['sha3'] = image
                        load_ns = hw.select('sha3')
                        if not load_ns or hw.info()[1] != 1:
                            raise RuntimeError('Fresh SHA3 reconfiguration was not observed')
                        with path.open('rb') as source:
                            warmup = hasher.hash_stream(source, WARMUP, 'sha3', verify=False)
                        if warmup['digest'] != report['reference']['warmup_prefix_sha3_256']:
                            raise RuntimeError('Warmup digest mismatch')
                        report['warmups'].append(dict(warmup,core=core,trial=index+1))
                        if fingerprint(path) != original:
                            raise RuntimeError('File changed before trial')
                        emit('trial_started', trial=index+1, core=core, bytes=SIZE)
                        result = measure(hasher, path)
                        if result['digest'] != report['reference']['sha3_256'] or fingerprint(path) != original:
                            raise RuntimeError('Full-file digest mismatch or input changed')
                        result.update(core=core,trial=index+1,image=image,verified=True,
                                      intermediate_algorithm_id=2,partial_load_ns=load_ns)
                        report['samples'].append(result); save(output, report)
                        emit('trial_complete',**result)
                finally:
                    hw = hasher._hardware; hw.manifest = deepcopy(base)
                    hw.select('sha256'); load_ns = hw.select('sha3')
                    restored = hasher.hash_bytes(b'', 'sha3', verify=True)
                    if not load_ns or hw.info()[1] != 1:
                        raise RuntimeError('Compact restoration was not observed')
                    report['restored_compact'] = dict(restored,partial_load_ns=load_ns)
                    safe_to_restart = True
        finally:
            if safe_to_restart:
                subprocess.run([starter,'start'],check=True,stdout=subprocess.DEVNULL)
            else:
                report['restoration_failed'] = True
        if not safe_to_restart:
            raise RuntimeError('Restoration failed; service remains stopped for recovery')
        report['summary'] = {}
        for core in ('oxide','compact'):
            samples = [s for s in report['samples'] if s['core']==core]
            report['summary'][core] = {key:statistics.median(s[key] for s in samples)
                                      for key in ('local_hash_ns','file_read_ns','dma_calls_ns')}
            report['summary'][core].update(min_ns=min(s['local_hash_ns'] for s in samples),
                                          max_ns=max(s['local_hash_ns'] for s in samples),
                                          MB_per_second=SIZE/(report['summary'][core]['local_hash_ns']/1e9)/1e6)
        report['profile_env_after'] = sha('/boot/profile.env')
        if report['profile_env_after'] != report['profile_env_before']:
            raise RuntimeError('Saved boot selection changed')
        report['service_status'] = subprocess.check_output([starter,'status'],text=True).strip()
        if 'running' not in report['service_status'].lower():
            raise RuntimeError('Hash service did not restart')
        report['state'] = 'passed'; save(output,report); emit('done',summary=report['summary'],report=str(output))
    except BaseException as error:
        report.update(state='failed',error=str(error));save(output,report);emit('failed',error=str(error));raise


if __name__ == '__main__':
    def interrupted(signum, frame):
        raise TimeoutError('Benchmark interrupted or exceeded its 30-minute bound')
    for sig in (signal.SIGTERM,signal.SIGINT,signal.SIGALRM):
        signal.signal(sig,interrupted)
    signal.alarm(1800)
    main()
